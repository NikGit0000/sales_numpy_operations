import numpy as np

prices = np.array([120, 250, 500, 750, 1000])
quantities = np.array([5, 3, 8, 2, 4])
discounts = np.array([10, 15, 0, 20, 5])


def info(arr):
    print("Масив:", arr)
    print("type:", type(arr))
    print("dtype:", arr.dtype)
    print("shape:", arr.shape)
    print("len:", len(arr), "size:", arr.size)
    print("Елементи:")
    for x in arr:
        print(x)
    print()


print("===== Розділ 2 =====")
info(prices)
info(quantities)
info(discounts)


print("===== Розділ 3 =====")
sales = prices * quantities
print("3.1 Вартість проданих товарів:", sales)

discounts = discounts + 3
print("3.2 Знижки +3%:", discounts)

new_prices = prices * (1 - discounts / 100)
print("3.3 Ціни після знижки:", new_prices)


print("===== Розділ 4 =====")
print("4.1 Більше 500:", prices[prices > 500])
print("4.2 Від 200 до 800:", prices[(prices >= 200) & (prices <= 800)])
print("4.3 Рівно 500:", prices[prices == 500])


print("===== Розділ 5 =====")
print("5.1 Менше 300 або більше 800:", prices[(prices < 300) | (prices > 800)])
print("5.2 Не більше 500:", prices[~(prices > 500)])
print("5.3 Ціна > 200 і продажів > 3:", prices[(prices > 200) & (quantities > 3)])


print("===== Розділ 6 =====")
discount_20 = prices * 0.2
print("6.1 Знижка 20%:", discount_20)

individual = prices * discounts / 100
print("6.2 Індивідуальна знижка:", individual)

final = prices - individual
print("6.3 Кінцева ціна:", final)


print("===== Розділ 7 =====")
print("7.1 Перша ціна:", prices[0])
print("7.1 Остання ціна:", prices[-1])
print("7.2 Перші три ціни:", prices[:3])

prices[1] = 300
print("7.3 Після зміни другої ціни:", prices)

print("7.4 У зворотному порядку:", prices[::-1])


print("===== Розділ 8 =====")
prices = np.append(prices, 1500)
print("8.1 Після append:", prices)

prices = np.insert(prices, 2, 400)
print("8.2 Після insert:", prices)

prices = np.delete(prices, 1)
print("8.3 Після delete:", prices)


print("===== Розділ 9 =====")
prices += 100
print("9.1 Після += 100:", prices)

quantities *= 2
print("9.2 Кількість після *= 2:", quantities)

print("9.3 Повні набори по 100:", prices // 100)
print("9.4 Залишок від ділення на 100:", prices % 100)

prices = np.where(prices < 300, 300, prices)
print("9.5 Після where:", prices)

print("9.6 Унікальні ціни:", np.unique(prices))

prices = np.sort(prices)
print("9.7 Після sort:", prices)

prices = np.clip(prices, 200, 800)
print("9.8 Після clip:", prices)